# PSQ[piece + 6][square]: material + table, from white's point of view.
PSQ = [[0] * 128 for _ in range(13)]
for _kind, _table in PST.items():
    for _s in SQUARES:
        _r, _f = _s >> 4, _s & 7
        PSQ[_kind + 6][_s] = VALUE[_kind] + _table[(7 - _r) * 8 + _f]
        PSQ[-_kind + 6][_s] = -(VALUE[_kind] + _table[_r * 8 + _f])


def evaluate(board):
    """Score in centipawns from the side to move's point of view."""
    b = board.sq
    score = 0
    for s in SQUARES:
        p = b[s]
        if p:
            score += PSQ[p + 6][s]
    return score * board.side
